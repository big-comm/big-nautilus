# Locale variants that share their parent language's translations verbatim.
# Each entry maps `<variant>` to its source language. We emit a `.po`/`.mo` for
# the variant by copying the source's strings, so e.g. a user with
# `LANG=pt_BR.UTF-8` finds `pt_BR/LC_MESSAGES/nautilus-terminal.mo` directly
# (in addition to the existing gettext fallback to plain `pt`).
#
# `pt`'s translations were authored in Brazilian Portuguese ("Gerenciador de
# arquivos"), so `pt_BR` is a faithful copy. `pt_PT` would need separate
# strings if/when someone contributes them.
LANGUAGE_ALIASES = {
    "pt_BR": "pt",
    "zh_CN": "zh",
    "zh_TW": "zh",
    "en_US": "en",
    "en_GB": "en",
}

ALIAS_LANGUAGE_NAMES = {
    "pt_BR": "Portuguese (Brazil)",
    "zh_CN": "Chinese (Simplified)",
    "zh_TW": "Chinese (Traditional)",
    "en_US": "English (United States)",
    "en_GB": "English (United Kingdom)",
}

LANGUAGES = list(LANGUAGE_NAMES.keys()) + list(LANGUAGE_ALIASES.keys())


def escape_po_string(s):
    """Escape string for .po file format."""
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def resolve_lang(lang):
    """Return the language code whose translations should be used for `lang`."""
    return LANGUAGE_ALIASES.get(lang, lang)


def lang_display_name(lang):
    """Human-readable name for the language, including alias-only ones."""
    if lang in ALIAS_LANGUAGE_NAMES:
        return ALIAS_LANGUAGE_NAMES[lang]
    return LANGUAGE_NAMES.get(lang, lang)


def generate_po_file(lang):
    """Generate a .po file for the given language."""
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M%z")
    lang_name = lang_display_name(lang)
    source_lang = resolve_lang(lang)

    lines = []
    lines.append(f'# {lang_name} translations for nautilus-terminal.')
    lines.append(f'# Copyright (C) 2025 The Nautilus Authors')
    lines.append(f'# This file is distributed under the same license as the nautilus package.')
    lines.append(f'#')
    lines.append(f'msgid ""')
    lines.append(f'msgstr ""')
    lines.append(f'"Project-Id-Version: nautilus-terminal 49.4\\n"')
    lines.append(f'"Report-Msgid-Bugs-To: \\n"')
    lines.append(f'"POT-Creation-Date: 2026-03-14 19:07-0300\\n"')
    lines.append(f'"PO-Revision-Date: 2026-03-14 19:07-0300\\n"')
    lines.append(f'"Last-Translator: Auto-generated\\n"')
    lines.append(f'"Language-Team: {lang_name}\\n"')
    lines.append(f'"Language: {lang}\\n"')
    lines.append(f'"MIME-Version: 1.0\\n"')
    lines.append(f'"Content-Type: text/plain; charset=UTF-8\\n"')
    lines.append(f'"Content-Transfer-Encoding: 8bit\\n"')
    lines.append('')

    for msgid, translations in TRANSLATIONS.items():
        msgstr = translations.get(source_lang, "")
        lines.append(f'msgid "{escape_po_string(msgid)}"')
        lines.append(f'msgstr "{escape_po_string(msgstr)}"')
        lines.append('')

    return '\n'.join(lines) + '\n'


def main():
    po_dir = os.path.dirname(os.path.abspath(__file__))
    locale_dir = os.path.join(po_dir, '..', 'data', 'locale')

    for lang in LANGUAGES:
        # Generate .po file
        po_content = generate_po_file(lang)
        po_path = os.path.join(po_dir, f'big-nautilus-terminal-{lang}.po')
        with open(po_path, 'w', encoding='utf-8') as f:
            f.write(po_content)
        print(f"Generated: {po_path}")

        # Compile .mo file
        mo_dir = os.path.join(locale_dir, lang, 'LC_MESSAGES')
        os.makedirs(mo_dir, exist_ok=True)
        mo_path = os.path.join(mo_dir, 'nautilus-terminal.mo')
        ret = os.system(f'msgfmt -o "{mo_path}" "{po_path}"')
        if ret == 0:
            print(f"Compiled: {mo_path}")
        else:
            print(f"ERROR compiling: {mo_path}")

    print(f"\nDone! Generated {len(LANGUAGES)} .po files and compiled .mo files.")


if __name__ == '__main__':
    main()
